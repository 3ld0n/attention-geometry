"""exp-132 — Theory-of-A Level 3: MLP Block-0 Position-Correlation Mechanism.

Pre-registration committed to attention-geometry at d7e27a4 before this script
was written or any forward passes run.

Tests whether MLP block 0's position-correlated write (σ=0.313, exp-131) is
inherited from its input h^(0.5) = h^(0) + attn_out^(0), or generated by the
MLP's nonlinearity.

Ariel — 2026-08-31.
"""
from __future__ import annotations

import importlib.util
import json
import sys
from pathlib import Path

import numpy as np
import torch
from transformers import AutoModelForCausalLM

HERE = Path(__file__).resolve().parent
EXP112 = HERE.parent / "exp-112_score_drift_decomposition"

spec = importlib.util.spec_from_file_location("exp112", EXP112 / "measure_scores.py")
sys.path.insert(0, str(EXP112.parent / "exp-107_natural_text_bilocal"))
exp112 = importlib.util.module_from_spec(spec)
spec.loader.exec_module(exp112)

pooled_window_profile = exp112.pooled_window_profile
ols_slope = exp112.ols_slope
WINDOW = exp112.WINDOW    # lags 8..256, 249 elements

SEQ_LEN = 512
N_SEQS = 50
SEED = 42
VOCAB_SIZE = 50257
PREREG_COMMIT = "d7e27a4"


def r2_of_slope(profile: np.ndarray, lags: np.ndarray) -> float:
    lx = np.log(lags.astype(float))
    X = np.column_stack([np.ones_like(lx), lx])
    c, *_ = np.linalg.lstsq(X, profile, rcond=None)
    y_pred = X @ c
    ss_tot = float(((profile - profile.mean()) ** 2).sum())
    ss_res = float(((profile - y_pred) ** 2).sum())
    return 1.0 - ss_res / ss_tot if ss_tot > 1e-12 else 0.0


def sigma_meanfirst(mean_arr: np.ndarray) -> tuple[float, float]:
    """σ from mean-over-sequences array (mean-first protocol)."""
    norms = np.linalg.norm(mean_arr, axis=-1, keepdims=True)
    norms = np.where(norms < 1e-10, 1.0, norms)
    M = mean_arr / norms
    C = M @ M.T
    profile = pooled_window_profile(C)
    sigma = -ols_slope(profile, WINDOW)
    r2 = r2_of_slope(profile, WINDOW)
    c8 = float(profile[0])
    return float(sigma), float(r2), c8


def main() -> None:
    print("exp-132: MLP Block-0 Position-Correlation Mechanism", flush=True)
    print(f"Pre-registration commit: {PREREG_COMMIT}\n", flush=True)

    device = "mps" if torch.backends.mps.is_available() else "cpu"
    print(f"Device: {device}", flush=True)

    model = AutoModelForCausalLM.from_pretrained(
        "gpt2", dtype=torch.float32,
        attn_implementation="eager").to(device).eval()

    # Random-token census — same protocol as exp-107, exp-131
    rng = np.random.RandomState(SEED)
    seqs_np = rng.randint(0, VOCAB_SIZE, size=(N_SEQS, SEQ_LEN))
    seqs = torch.tensor(seqs_np, dtype=torch.long, device=device)
    print(f"Random-token sequences: {N_SEQS} × {SEQ_LEN}  seed={SEED}", flush=True)

    # Mean-first accumulators: h0, attn0, mlp0
    acc = {k: np.zeros((SEQ_LEN, 768), dtype=np.float64)
           for k in ["h0", "attn0", "mlp0"]}

    handles = []
    _buf: dict[str, np.ndarray] = {}

    def hook_h0(module, args):
        """Capture block-0 input (embedding = token + position embeddings)."""
        _buf["h0"] = args[0].detach().float().cpu().numpy()[0]

    def hook_attn0(module, args, output):
        """Capture block-0 attention output write."""
        out = output[0] if isinstance(output, tuple) else output
        _buf["attn0"] = out.detach().float().cpu().numpy()[0]

    def hook_mlp0(module, args, output):
        """Capture block-0 MLP output write."""
        out = output if not isinstance(output, tuple) else output[0]
        _buf["mlp0"] = out.detach().float().cpu().numpy()[0]

    handles.append(model.transformer.h[0].register_forward_pre_hook(hook_h0))
    handles.append(model.transformer.h[0].attn.register_forward_hook(hook_attn0))
    handles.append(model.transformer.h[0].mlp.register_forward_hook(hook_mlp0))

    with torch.no_grad():
        for i, seq in enumerate(seqs):
            if (i + 1) % 10 == 0:
                print(f"  Sequence {i+1}/{N_SEQS}...", flush=True)
            _buf.clear()
            model(seq.unsqueeze(0))

            h0_s    = _buf["h0"].astype(np.float64)
            attn0_s = _buf["attn0"].astype(np.float64)
            mlp0_s  = _buf["mlp0"].astype(np.float64)

            acc["h0"]    += h0_s    / N_SEQS
            acc["attn0"] += attn0_s / N_SEQS
            acc["mlp0"]  += mlp0_s  / N_SEQS

    for h in handles:
        h.remove()

    # h^(0.5) = h^(0) + attn_out^(0)  (MLP input)
    acc["h0p5"] = acc["h0"] + acc["attn0"]

    print("\n=== Mean-first cosine protocol (σ measurements) ===", flush=True)
    results_sigma = {}
    for key in ["h0", "attn0", "h0p5", "mlp0"]:
        sigma, r2, c8 = sigma_meanfirst(acc[key])
        results_sigma[key] = {"sigma": sigma, "r2": r2, "c8": c8}
        label = {
            "h0":    "h^(0)     [embedding]",
            "attn0": "attn_out^(0) [block-0 attn write]",
            "h0p5":  "h^(0.5)   [MLP input = h^(0)+attn0]",
            "mlp0":  "mlp_out^(0)  [block-0 MLP write]",
        }[key]
        print(f"  {label:42s}  σ={sigma:+.4f}  R²={r2:.4f}  C[8]={c8:.3f}", flush=True)

    sigma_h0p5 = results_sigma["h0p5"]["sigma"]
    sigma_mlp0 = results_sigma["mlp0"]["sigma"]
    sigma_h0   = results_sigma["h0"]["sigma"]
    sigma_attn0 = results_sigma["attn0"]["sigma"]

    # Registered predictions
    sigma_exp131_mlp0 = 0.313   # from exp-131

    P1_ok = sigma_h0p5 >= 0.28
    P2_ok = sigma_h0p5 > sigma_h0
    P3_ok = 0.29 <= sigma_mlp0 <= 0.34

    K1_fired = sigma_h0p5 < 0.20
    K2_fired = sigma_mlp0 < 0.28 or sigma_mlp0 > 0.35

    print(f"\n=== Registered predictions ===", flush=True)
    print(f"  P1 (σ(h^0.5) ≥ 0.28):              σ={sigma_h0p5:.4f}  → {'OK' if P1_ok else 'FAIL'}", flush=True)
    print(f"  P2 (σ(h^0.5) > σ(h^0)):            {sigma_h0p5:.4f} > {sigma_h0:.4f}  → {'OK' if P2_ok else 'FAIL'}", flush=True)
    print(f"  P3 (σ_mlp0 ∈ [0.29, 0.34]):        σ={sigma_mlp0:.4f}  → {'OK' if P3_ok else 'FAIL'}", flush=True)
    print(f"  K1 (σ(h^0.5) < 0.20):              {'FIRED' if K1_fired else 'ok'}", flush=True)
    print(f"  K2 (σ_mlp0 ∉ [0.28, 0.35]):        {'FIRED' if K2_fired else 'ok'}", flush=True)

    # Amplification ratio (if P3 holds; informative not pre-registered)
    if P3_ok and sigma_h0p5 > 0.01:
        ratio = sigma_mlp0 / sigma_h0p5
        print(f"\n  Amplification ratio σ_mlp0/σ(h^0.5) = {ratio:.3f}  "
              f"({'pass-through' if ratio < 1.15 else 'amplification'})", flush=True)

    # Verdict
    if K2_fired:
        overall = "inconclusive"
        note = "K2: exp-131 not reproduced; protocol issue"
    elif K1_fired:
        overall = "inconclusive"
        note = "K1: σ(h^0.5) < 0.20; MLP generates structure from low-σ input"
    elif P1_ok and P3_ok:
        overall = "confirmed"
        note = "Pass-through: MLP output structure inherited from h^(0.5)"
    elif P3_ok:
        overall = "partial"
        note = "Moderate structure in MLP input; MLP amplifies meaningfully"
    else:
        overall = "inconclusive"
        note = "P3 not confirmed; exp-131 not reproduced"

    print(f"\n  Overall verdict: {overall.upper()} — {note}", flush=True)

    results = {
        "exp": "exp-132",
        "date": "2026-08-31",
        "prereg_commit": PREREG_COMMIT,
        "model": "gpt2",
        "n_seqs": N_SEQS,
        "seq_len": SEQ_LEN,
        "seed": SEED,
        "data": "random-token census (uniform [0, 50257), seed=42)",
        "protocol": "mean-first cosine",
        "sigma_results": results_sigma,
        "exp131_reference": {
            "sigma_mlp0": sigma_exp131_mlp0,
            "sigma_attn0": 0.132,
            "sigma_delta_total": 0.258,
        },
        "registered_predictions": {
            "P1": {"ok": P1_ok, "sigma_h0p5": float(sigma_h0p5),
                   "criterion": "sigma(h^0.5) >= 0.28"},
            "P2": {"ok": P2_ok, "sigma_h0p5": float(sigma_h0p5),
                   "sigma_h0": float(sigma_h0),
                   "criterion": "sigma(h^0.5) > sigma(h^0)"},
            "P3": {"ok": P3_ok, "sigma_mlp0": float(sigma_mlp0),
                   "criterion": "sigma_mlp0 in [0.29, 0.34] (exp-131 reproduced)"},
        },
        "kill_conditions": {
            "K1": {"fired": K1_fired, "sigma_h0p5": float(sigma_h0p5),
                   "criterion": "sigma(h^0.5) < 0.20"},
            "K2": {"fired": K2_fired, "sigma_mlp0": float(sigma_mlp0),
                   "criterion": "sigma_mlp0 not in [0.28, 0.35]"},
        },
        "overall_verdict": overall,
        "verdict_note": note,
    }

    out = HERE / "results.json"
    out.write_text(json.dumps(results, indent=2))
    print(f"\nWrote {out}", flush=True)


if __name__ == "__main__":
    main()
